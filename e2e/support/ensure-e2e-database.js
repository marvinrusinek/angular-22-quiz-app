/**
 * Create this run's throwaway database, immediately before the backend starts.
 *
 * WHY THIS IS NOT IN globalSetup: Playwright launches `webServer` BEFORE
 * globalSetup, so a database created there does not exist yet when the backend
 * opens its pool — the server exits with `database "e2e_…" does not exist` and
 * the whole run fails before a single test. SQLite hid this ordering entirely,
 * because it creates its file on demand.
 *
 * Running as part of the webServer command makes the ordering a fact rather
 * than an assumption.
 *
 * Plain JavaScript on purpose: this runs via the shell in front of `npm run
 * dev`, with no transpiler in the chain.
 */
const { execFileSync } = require('node:child_process');
const { Client } = require('pg');

const { assertSafeSeedTarget } = require('./seed-target-guard');

const NAME_PREFIX = 'e2e_';

const name = (process.env.E2E_DATABASE_NAME || '').trim();
const adminUrl = (process.env.E2E_ADMIN_DATABASE_URL || '').trim();

function fail(message) {
  console.error(`[e2e-db] ${message}`);
  process.exit(1);
}

if (!name) fail('E2E_DATABASE_NAME is not set');
if (!adminUrl) fail('E2E_ADMIN_DATABASE_URL is not set');

// The same guard the TypeScript harness applies: only ever create a database
// this harness generated.
if (!name.startsWith(NAME_PREFIX)) {
  fail(`refusing to create a database not named ${NAME_PREFIX}*: ${name}`);
}

(async () => {
  const client = new Client({
    connectionString: adminUrl,
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: 30_000
  });
  await client.connect();
  try {
    const { rows } = await client.query('SELECT 1 FROM pg_database WHERE datname = $1', [name]);
    if (rows.length === 0) {
      // Identifiers cannot be parameterized. The name is generated by the
      // harness and validated above, so it is never user input.
      await client.query(`CREATE DATABASE "${name}"`);
      console.log(`[e2e-db] created throwaway database ${name}`);
    } else {
      console.log(`[e2e-db] reusing throwaway database ${name}`);
    }
  } finally {
    await client.end();
  }

  seedQuizBank();
})().catch((err) => fail(`could not create ${name}: ${err.message}`));

/**
 * Import the quiz bank into the throwaway database.
 *
 * REQUIRED since the backend became PostgreSQL-authoritative: it now fails
 * closed on an empty bank ("No quizzes found in PostgreSQL"), so a freshly
 * created E2E database would stop the server booting and take the whole run
 * with it. Creating the database is no longer enough — it has to be populated.
 *
 * Runs the real import script rather than reimplementing it, so E2E exercises
 * the same validation and the same derived ids as production. The connection is
 * passed EXPLICITLY: the import script loads `.env` when present, and relying on
 * environment precedence to keep it pointed at the throwaway database would be
 * one silent mistake away from writing to the developer's own.
 */
function seedQuizBank() {
  const databaseUrl = (process.env.DATABASE_URL || '').trim();

  // Fail closed unless this URL targets exactly THIS run's throwaway database.
  // Seeding runs the import, which deletes and reinserts every question, so a
  // wrong target would silently rewrite the developer's own data. The guard is
  // a pure function with its own unit tests — see seed-target-guard.test.js.
  try {
    assertSafeSeedTarget(databaseUrl, name);
  } catch (err) {
    fail(err.message);
  }
  try {
    execFileSync(
      process.execPath,
      [
        '--require', 'ts-node/register',
        'scripts/import-quiz-bank.ts',
        // Stage 15: E2E seeds from the SAME deterministic synthetic bank the
        // backend's own tests use (test/helpers/synthetic-quiz-bank.json) —
        // never the real private bank, and never a file that must exist in
        // the repo for E2E to run. See that file's own doc comment for the
        // structural shapes (single/multiple/trueFalse, an exactly-3-correct
        // multi-answer question, "All of the above", facts, an option-id
        // collision) each E2E spec relies on.
        '--file', './test/helpers/synthetic-quiz-bank.json',
        '--database-url', databaseUrl
      ],
      { cwd: process.cwd(), stdio: 'inherit' }
    );
  } catch (err) {
    fail(`quiz-bank import failed: ${err.message}`);
  }
}
